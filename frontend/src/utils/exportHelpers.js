/**
 * Utilities for exporting RepoLens reports as Markdown and CONTRIBUTING.md files.
 */

/**
 * Trigger a browser file download from string content.
 * @param {string} filename
 * @param {string} content
 * @param {string} mimeType
 */
export function downloadTextFile(filename, content, mimeType = 'text/markdown;charset=utf-8') {
  if (typeof window === 'undefined') return;
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

/**
 * Generate a comprehensive Markdown audit report.
 * @param {object} report
 * @returns {string}
 */
export function generateMarkdownReport(report) {
  if (!report || !report.repo) return '';

  const { repo, health_score, summary, architecture_diagram, onboarding_guide } = report;
  const dateStr = new Date(report.created_at || Date.now()).toUTCString();
  const origin = typeof window !== 'undefined' ? window.location.origin : 'http://localhost:5173';
  const badgeUrl = `${origin}/api/badge/${repo.owner}/${repo.name}.svg`;
  const reportUrl = `${origin}/?repo=${encodeURIComponent(`${repo.owner}/${repo.name}`)}`;

  let md = `# RepoLens Health & Architecture Audit: ${repo.owner}/${repo.name}\n\n`;
  md += `> **Audit Generated by [RepoLens](${reportUrl}) on ${dateStr}**\n\n`;
  md += `[![RepoLens Health](${badgeUrl})](${reportUrl})\n\n`;

  // Overview
  md += `## 1. Repository Overview\n\n`;
  md += `- **Repository**: [${repo.owner}/${repo.name}](${repo.url})\n`;
  md += `- **Description**: ${repo.description || 'No description provided.'}\n`;
  md += `- **Primary Language**: ${repo.language || 'Unknown'}\n`;
  md += `- **License**: ${repo.license_name || 'None detected'}\n`;
  md += `- **Community**: ⭐ ${repo.stars?.toLocaleString() || 0} stars | 🍴 ${repo.forks?.toLocaleString() || 0} forks | ⚠️ ${repo.open_issues?.toLocaleString() || 0} open issues\n\n`;

  // Summary
  if (summary) {
    md += `## 2. Repository Intelligence Summary\n\n`;
    if (summary.one_line_summary) {
      md += `**TL;DR**: ${summary.one_line_summary}\n\n`;
    }
    if (summary.what_it_does) {
      md += `### What It Does\n${summary.what_it_does}\n\n`;
    }
    if (summary.tech_stack && summary.tech_stack.length > 0) {
      md += `### Tech Stack\n${summary.tech_stack.map((t) => `- **${t.name}** (${t.category}): ${t.purpose}`).join('\n')}\n\n`;
    }
    if (summary.standout_features && summary.standout_features.length > 0) {
      md += `### Key Capabilities\n${summary.standout_features.map((f) => `- ${f}`).join('\n')}\n\n`;
    }
  }

  // Health Score
  if (health_score) {
    md += `## 3. Health & Maintainability Score: ${health_score.overall_score}/100 (Grade: ${health_score.grade})\n\n`;
    md += `| Category | Score | Max | Weight | Status | Findings |\n`;
    md += `| :--- | :---: | :---: | :---: | :---: | :--- |\n`;

    if (health_score.breakdown) {
      Object.entries(health_score.breakdown).forEach(([key, cat]) => {
        const name = cat.name || key;
        const score = cat.score ?? '-';
        const max = cat.max_score ?? '-';
        const weight = cat.weight ? `${Math.round(cat.weight * 100)}%` : '-';
        const status = cat.passed ? '✅ Passed' : '⚠️ Needs Attention';
        const reason = (cat.reason || '').replace(/\|/g, '\\|');
        md += `| **${name}** | ${score} | ${max} | ${weight} | ${status} | ${reason} |\n`;
      });
      md += `\n`;
    }

    if (health_score.recommendations && health_score.recommendations.length > 0) {
      md += `### Actionable Recommendations for Maintainers\n\n`;
      health_score.recommendations.forEach((rec, idx) => {
        md += `${idx + 1}. **${rec.title || 'Improvement'}**: ${rec.description || rec}\n`;
      });
      md += `\n`;
    }
  }

  // Architecture Diagram
  if (architecture_diagram) {
    md += `## 4. Architecture & System Flow Diagram\n\n`;
    md += `\`\`\`mermaid\n${architecture_diagram}\n\`\`\`\n\n`;
  }

  // Onboarding Guide
  if (onboarding_guide) {
    md += `## 5. Contributor Onboarding Guide\n\n`;
    if (onboarding_guide.prerequisites && onboarding_guide.prerequisites.length > 0) {
      md += `### Prerequisites\n`;
      onboarding_guide.prerequisites.forEach((p) => {
        md += `- ${p}\n`;
      });
      md += `\n`;
    }

    if (onboarding_guide.setup_steps && onboarding_guide.setup_steps.length > 0) {
      md += `### Setup & Installation\n\`\`\`bash\n`;
      onboarding_guide.setup_steps.forEach((step) => {
        md += `# ${step.description || step.title || 'Step'}\n${step.command || step}\n\n`;
      });
      md += `\`\`\`\n\n`;
    }

    if (onboarding_guide.run_command) {
      md += `### Running Locally\n\`\`\`bash\n${onboarding_guide.run_command}\n\`\`\`\n\n`;
    }

    if (onboarding_guide.test_command) {
      md += `### Running Tests\n\`\`\`bash\n${onboarding_guide.test_command}\n\`\`\`\n\n`;
    }
  }

  md += `---\n\n`;
  md += `*Generated automatically by [RepoLens](https://github.com/yashwantraj147-eng/repolens) — Instant Architecture Diagrams & Health Audits for GitHub Repositories.*\n`;

  return md;
}

/**
 * Generate a ready-to-use CONTRIBUTING.md file.
 * @param {object} report
 * @returns {string}
 */
export function generateContributingGuide(report) {
  if (!report || !report.repo) return '';

  const { repo, onboarding_guide } = report;
  let md = `# Contributing to ${repo.name}\n\n`;
  md += `Thank you for considering contributing to **${repo.name}**! This document provides instructions to help you get your development environment set up and submit pull requests cleanly.\n\n`;

  if (onboarding_guide) {
    if (onboarding_guide.prerequisites && onboarding_guide.prerequisites.length > 0) {
      md += `## Prerequisites\n\n`;
      md += `Before starting, make sure you have installed:\n\n`;
      onboarding_guide.prerequisites.forEach((p) => {
        md += `- ${p}\n`;
      });
      md += `\n`;
    }

    md += `## Getting Started\n\n`;
    md += `1. Fork the repository on GitHub.\n`;
    md += `2. Clone your fork locally:\n`;
    md += `   \`\`\`bash\n   git clone ${repo.url}.git\n   cd ${repo.name}\n   \`\`\`\n`;

    if (onboarding_guide.setup_steps && onboarding_guide.setup_steps.length > 0) {
      md += `3. Install dependencies and set up the environment:\n   \`\`\`bash\n`;
      onboarding_guide.setup_steps.forEach((s) => {
        md += `   ${s.command || s}\n`;
      });
      md += `   \`\`\`\n\n`;
    }

    if (onboarding_guide.run_command) {
      md += `## Running the Project Locally\n\n\`\`\`bash\n${onboarding_guide.run_command}\n\`\`\`\n\n`;
    }

    if (onboarding_guide.test_command) {
      md += `## Running Tests\n\nBefore submitting your code, please run the test suite:\n\n\`\`\`bash\n${onboarding_guide.test_command}\n\`\`\`\n\n`;
    }
  }

  md += `## Pull Request Workflow\n\n`;
  md += `1. Create a feature branch: \`git checkout -b feature/my-new-feature\`\n`;
  md += `2. Commit your changes: \`git commit -m 'feat: add awesome feature'\`\n`;
  md += `3. Push to your branch: \`git push origin feature/my-new-feature\`\n`;
  md += `4. Open a Pull Request with a clear description of your changes.\n\n`;
  md += `---\n*Generated by [RepoLens](https://github.com/yashwantraj147-eng/repolens).*\n`;

  return md;
}
